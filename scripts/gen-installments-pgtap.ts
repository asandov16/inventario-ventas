/**
 * Generates supabase/tests/20_calc_installments.sql from shared/fixtures/installments.cases.json,
 * so private.calc_installments (SQL) and the TypeScript preview are tested against the same
 * cases (ADR-034). CI regenerates it and fails if the committed file differs.
 *
 * Usage: pnpm gen:installment-tests
 */
import { readFileSync, writeFileSync } from 'node:fs';

interface Installment {
  number: number;
  dueDate: string;
  amount: number;
}

interface FixtureCase {
  id: string;
  input: {
    total: number;
    downPayment: number;
    months: number;
    saleDate: string;
    firstDueDate?: string;
  };
  expected: { installments: Installment[] } | { error: string };
}

const FIXTURE_PATH = 'shared/fixtures/installments.cases.json';
const OUTPUT_PATH = 'supabase/tests/20_calc_installments.sql';

const fixture = JSON.parse(readFileSync(FIXTURE_PATH, 'utf8')) as { cases: FixtureCase[] };

const sqlString = (value: string): string => `'${value.replaceAll("'", "''")}'`;

function callFor({ input }: FixtureCase): string {
  const firstDue = input.firstDueDate ? `${sqlString(input.firstDueDate)}::date` : 'null';
  return (
    `private.calc_installments(${String(input.total)}, ${String(input.downPayment)}, ` +
    `${String(input.months)}, ${sqlString(input.saleDate)}::date, ${firstDue})`
  );
}

function testFor(fixtureCase: FixtureCase): string {
  const call = callFor(fixtureCase);
  if ('error' in fixtureCase.expected) {
    return [
      `select throws_ok(`,
      `    ${sqlString(`select * from ${call}`)},`,
      `    'P0001', ${sqlString(fixtureCase.expected.error)},`,
      `    ${sqlString(fixtureCase.id)}`,
      `);`,
    ].join('\n');
  }
  const rows = fixtureCase.expected.installments
    .map(
      (i) => `(${String(i.number)}::smallint, ${sqlString(i.dueDate)}::date, ${String(i.amount)})`,
    )
    .join(', ');
  return [
    `select results_eq(`,
    `    ${sqlString(`select number, due_date, amount from ${call} order by number`)},`,
    `    ${sqlString(`values ${rows}`)},`,
    `    ${sqlString(fixtureCase.id)}`,
    `);`,
  ].join('\n');
}

const output = [
  '-- GENERATED by scripts/gen-installments-pgtap.ts from shared/fixtures/installments.cases.json.',
  '-- Do not edit by hand: change the fixture and run `pnpm gen:installment-tests`.',
  'begin;',
  `select plan(${String(fixture.cases.length)});`,
  '',
  ...fixture.cases.map(testFor).flatMap((block) => [block, '']),
  'select * from finish();',
  'rollback;',
  '',
].join('\n');

writeFileSync(OUTPUT_PATH, output);
console.warn(`Wrote ${OUTPUT_PATH} with ${String(fixture.cases.length)} cases`);
